// ── Bengali amount in words ──────────────────────────────────────────────────
function bnMoneyWords(amount) {
    if (!isFinite(amount)) return '';
    const ones = ['', 'এক', 'দুই', 'তিন', 'চার', 'পাঁচ', 'ছয়', 'সাত', 'আট', 'নয়', 'দশ',
        'এগারো', 'বারো', 'তেরো', 'চৌদ্দ', 'পনেরো', 'ষোল', 'সতেরো', 'আঠারো', 'উনিশ', 'বিশ',
        'একুশ', 'বাইশ', 'তেইশ', 'চব্বিশ', 'পঁচিশ', 'ছাব্বিশ', 'সাতাশ', 'আঠাশ', 'ঊনত্রিশ', 'ত্রিশ',
        'একত্রিশ', 'বত্রিশ', 'তেত্রিশ', 'চৌত্রিশ', 'পঁয়ত্রিশ', 'ছত্রিশ', 'সাঁইত্রিশ', 'আটত্রিশ', 'ঊনচল্লিশ', 'চল্লিশ',
        'একচল্লিশ', 'বিয়াল্লিশ', 'তেতাল্লিশ', 'চুয়াল্লিশ', 'পঁয়তাল্লিশ', 'ছেচল্লিশ', 'সাতচল্লিশ', 'আটচল্লিশ', 'ঊনপঞ্চাশ', 'পঞ্চাশ',
        'একান্ন', 'বাহান্ন', 'তিপ্পান্ন', 'চুয়ান্ন', 'পঞ্চান্ন', 'ছাপ্পান্ন', 'সাতান্ন', 'আটান্ন', 'ঊনষাট', 'ষাট',
        'একষট্টি', 'বাষট্টি', 'তেষট্টি', 'চৌষট্টি', 'পঁয়ষট্টি', 'ছেষট্টি', 'সাতষট্টি', 'আটষট্টি', 'ঊনসত্তর', 'সত্তর',
        'একাত্তর', 'বাহাত্তর', 'তিয়াত্তর', 'চুয়াত্তর', 'পঁচাত্তর', 'ছিয়াত্তর', 'সাতাত্তর', 'আটাত্তর', 'ঊনআশি', 'আশি',
        'একাশি', 'বিরাশি', 'তিরাশি', 'চুরাশি', 'পঁচাশি', 'ছিয়াশি', 'সাতাশি', 'আটাশি', 'ঊনানব্বই', 'নব্বই',
        'একানব্বই', 'বিরানব্বই', 'তিরানব্বই', 'চুরানব্বই', 'পঁচানব্বই', 'ছিয়ানব্বই', 'সাতানব্বই', 'আটানব্বই', 'নিরানব্বই'];

    function below100(n) { return ones[n] || ''; }
    function words(n) {
        if (n === 0) return '';
        let out = '';
        if (n >= 10000000) { out += words(Math.floor(n / 10000000)) + ' কোটি '; n %= 10000000; }
        if (n >= 100000)   { out += below100(Math.floor(n / 100000)) + ' লক্ষ ';  n %= 100000; }
        if (n >= 1000)     { out += below100(Math.floor(n / 1000)) + ' হাজার ';   n %= 1000; }
        if (n >= 100)      { out += below100(Math.floor(n / 100)) + 'শত ';        n %= 100; }
        out += below100(n);
        return out.trim();
    }

    const taka  = Math.floor(Math.abs(amount));
    const poysha = Math.round((Math.abs(amount) - taka) * 100);
    let str = taka === 0 ? 'শূন্য' : words(taka);
    str += ' টাকা';
    if (poysha > 0) str += ' ' + words(poysha) + ' পয়সা';
    return str + ' মাত্র';
}
